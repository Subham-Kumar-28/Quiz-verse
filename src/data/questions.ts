/**
 * Randomize the order of options (A, B, C, D) for a question
 * and appropriately recalculate the correctIndex and wrongExplanations mapping.
 */
export function shuffleQuestionOptions(q: Question): Question {
  const originalCorrectText = q.options[q.correctIndex];

  // Map each option with its original index
  const indexed = q.options.map((text, idx) => ({
    text,
    originalIdx: idx,
  }));

  // Fisher-Yates shuffle algorithm
  for (let i = indexed.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [indexed[i], indexed[j]] = [indexed[j], indexed[i]];
  }

  const newCorrectIndex = indexed.findIndex((item) => item.text === originalCorrectText);

  const newWrongExplanations: Record<number, string> = {};
  if (q.wrongExplanations) {
    indexed.forEach((item, newIdx) => {
      if (newIdx !== newCorrectIndex && q.wrongExplanations?.[item.originalIdx]) {
        newWrongExplanations[newIdx] = q.wrongExplanations[item.originalIdx];
      }
    });
  }

  return {
    ...q,
    options: indexed.map((item) => item.text) as [string, string, string, string],
    correctIndex: newCorrectIndex,
    wrongExplanations: newWrongExplanations,
  };
}

/**
 * Filter questions for a quiz based on subject and difficulty.
 * Guarantees exactly 10 questions with randomized options across A, B, C, and D.
 * Prioritizes unseen questions so the user gets fresh, different questions every time.
 */
export function getQuizQuestions(
  subjectId: SubjectId | 'all',
  standard?: string,
  shuffle: boolean = true
): Question[] {
  let pool: Question[] = [];

  if (subjectId === 'all') {
    pool = [...ALL_QUESTIONS];
  } else {
    pool = ALL_QUESTIONS.filter((q) => q.subject === subjectId);
    // If fewer than 10 questions for this specific subject, supplement from general CS or related topics
    if (pool.length < 10) {
      const extra = ALL_QUESTIONS.filter((q) => q.subject !== subjectId);
      pool = [...pool, ...extra];
    }
  }

  // If specific standard was chosen and enough questions exist, prefer that standard
  if (standard) {
    const standardMatches = pool.filter((q) => q.standard === standard);
    if (standardMatches.length >= 10) {
      pool = standardMatches;
    }
  }

  // Anti-repeat algorithm: prioritize questions that the user has not seen recently
  const recentIds = new Set(getRecentlySeenQuestionIds(subjectId));
  const unseen = pool.filter((q) => !recentIds.has(q.id));
  const seen = pool.filter((q) => recentIds.has(q.id));

  let selected: Question[] = [];

  if (unseen.length >= 10) {
    // We have at least 10 brand-new questions!
    const shuffledUnseen = shuffle ? [...unseen].sort(() => Math.random() - 0.5) : unseen;
    selected = shuffledUnseen.slice(0, 10);
  } else {
    // Take all unseen questions, and supplement with shuffled seen questions (oldest seen)
    const shuffledUnseen = shuffle ? [...unseen].sort(() => Math.random() - 0.5) : unseen;
    const shuffledSeen = shuffle ? [...seen].sort(() => Math.random() - 0.5) : seen;
    selected = [...shuffledUnseen, ...shuffledSeen].slice(0, 10);
  }

  // Ensure unique questions if pool was somehow less than 10
  if (selected.length < 10) {
    for (const q of ALL_QUESTIONS) {
      if (!selected.find((existing) => existing.id === q.id)) {
        selected.push(q);
      }
      if (selected.length === 10) break;
    }
  }

  const finalQuestions = selected.slice(0, 10);

  // Record these question IDs into recently seen history so next attempt gives different questions!
  recordSeenQuestionIds(subjectId, finalQuestions.map((q) => q.id));

  // Randomize the A, B, C, D options for each question so the correct answer is evenly and randomly distributed
  return shuffle ? finalQuestions.map((q) => shuffleQuestionOptions(q)) : finalQuestions;
}
